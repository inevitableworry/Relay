#!/usr/bin/env python3
"""Original Relay UI chimes; NOT extracted PlayStation / Sony sound effects.

Produce eight short, non-looping cues with deterministic synthesis. Reference
footage informs UI *event types* but no third-party audio is sampled or copied.
OGG assets are loaded only when the user enables Navigation Sounds.
"""
from pathlib import Path
import math
import subprocess
import tempfile
import wave
import numpy as np

ROOT=Path(__file__).resolve().parents[1]
OUTPUT=ROOT/"android/app/src/main/assets/portal_audio"
OUTPUT.mkdir(parents=True,exist_ok=True)
SR=48000
RNG=np.random.default_rng(2300)


def tone(t, lo, hi, phase=0):
    duration=max(float(t[-1]),1/SR)
    phase_values=(lo*t+(hi-lo)*t*t/(2*duration))
    return np.sin(2*np.pi*phase_values+phase)


def sound(name,duration,lo,hi,noise_level=0.04,second=0.15,echo=0):
    n=round(duration*SR)
    t=np.arange(n,dtype=np.float64)/SR
    attack=np.minimum(t/.025,1)
    release=np.minimum((duration-t)/max(duration*.48,.03),1)
    envelope=np.clip(attack*release,0,1)**1.3
    noise=RNG.standard_normal(n)
    # Smooth noisy transients into an airy sweep, not a harsh UI click.
    noise=np.convolve(noise,np.ones(15)/15,mode='same')
    out=(tone(t,lo,hi)+second*tone(t,lo*2.02,hi*1.985)+
         noise_level*noise)*envelope
    if echo>0:
        delay=int(SR*echo)
        out[delay:]+=0.24*out[:-delay].copy()
    out=np.clip(out*.23,-.7,.7)
    with tempfile.TemporaryDirectory(prefix='relay-ui-') as folder:
        wav=Path(folder)/'source.wav'
        with wave.open(str(wav),'wb') as w:
            w.setnchannels(1);w.setsampwidth(2);w.setframerate(SR)
            w.writeframes((out*32767).astype('<i2').tobytes())
        target=OUTPUT/name
        subprocess.run(['ffmpeg','-hide_banner','-loglevel','error','-y',
                        '-i',str(wav),'-c:a','libvorbis','-q:a','4',str(target)],check=True)
    print(name,target.stat().st_size)


sound('menu_focus.ogg',.11,660,870,0.008)
sound('menu_confirm.ogg',.18,510,800,0.015,echo=.065)
sound('menu_back.ogg',.16,700,470,0.018)
sound('menu_open.ogg',.30,290,690,0.065,echo=.08)
sound('menu_close.ogg',.25,650,310,0.045)
sound('menu_reveal.ogg',.68,260,890,0.085,echo=.12)
sound('update_start.ogg',.37,420,685,0.045)
sound('update_complete.ogg',.52,500,940,0.042,echo=.14)

(OUTPUT/'CUE_SOURCE.txt').write_text(
    'Original Relay menu sounds, generated by tools/generate-relay-ui-cues.py.\n'
    'Deterministic synthesized tones/noise created for this app; they are NOT\n'
    'authentic PlayStation Portal firmware sounds and contain no Sony samples.\n'
    'Designed for personal interface previews. This does not grant rights to\n'
    'third-party PlayStation recordings or ambient background music.\n',
    encoding='utf-8'
)
